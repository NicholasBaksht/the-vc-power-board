/* ============================================================
   DATA-PARTNER-PHOTOS.JS
   ------------------------------------------------------------
   Portraits that may lawfully be published, and only those.

   Every entry below was established in two independent steps, and
   an entry that failed either one is simply absent:

     IDENTITY  the person was matched through Wikidata or an English
               Wikipedia article, and confirmed against their firm.
               Name matching alone is not enough: it produced a
               photograph of the Pursuit of Happyness Chris Gardner
               for Underscore VC's Chris Gardner, and of Marissa
               Mayer for Zachary Bogue, whose article redirects to
               hers. Both were rejected, along with a redirect to a
               company article. Publishing the wrong person's face is
               the worst failure available here, so the bar is
               corroboration, not resemblance.

     LICENCE   the file's licence was read from Wikimedia Commons and
               is one that permits republication with attribution.
               Fair-use and no-metadata files were dropped even where
               the identity was certain, and GFDL was dropped because
               honouring it means reproducing the full licence text.

   73 of 914 partners qualify. That is not a shortfall in the search;
   it is how many venture investors have a freely licensed portrait in
   existence. Everyone else renders a monogram, which partner-profile.js
   treats as the correct output rather than a missing one.

   To add someone by hand, the shape is the same, and `licence` must
   name a real grant you actually hold:

     'jane-smith': { file: 'assets/partners/jane-smith.jpg',
       credit: 'Acme Capital', licence: 'Press kit, editorial use',
       source: 'https://acme.vc/press' }

   The credit and licence render under the photograph. That is the
   attribution these licences require, so removing it breaks the terms
   the image is published under.
   ============================================================ */

